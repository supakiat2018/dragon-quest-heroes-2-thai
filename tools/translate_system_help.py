def apply_translation():
    file_path = "text_csv/categories/entry_00162_System_Help.csv"
    with open(file_path, "r", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for row_idx, thai_text in SYSTEM_HELP_THAI.items():
        if row_idx < len(rows):
            rows[row_idx]["ThaiTranslation"] = thai_text
            updated += 1

    with open(file_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[SUCCESS] Updated {updated} system help entries in {file_path}")

if __name__ == "__main__":
    apply_translation()
