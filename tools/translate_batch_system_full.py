    path = os.path.join(CATEGORIES_DIR, filename)
    df = pd.read_csv(path)
    df['ThaiTranslation'] = df['ThaiTranslation'].astype(object)
    count = 0
    for idx, row in df.iterrows():
        key = row['StringIndex'] if by == 'index' else row['OriginalEnglish']
        if key in mapping:
            df.at[idx, 'ThaiTranslation'] = mapping[key]
            count += 1
    df.to_csv(path, index=False, encoding='utf-8-sig')
    print(f"Updated {count} rows in {filename}")

