def update_csv():
    fname = "text_csv/categories/entry_00518_DLC_Epilogue_Stories.csv"
    with open(fname, mode='r', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for row in rows:
        idx = int(row['StringIndex'])
        if idx in translations_p1c:
            row['ThaiTranslation'] = translations_p1c[idx]
            updated += 1

    with open(fname, mode='w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Successfully updated {updated} rows in entry_00518 for Part 1C!")

if __name__ == '__main__':
    update_csv()
