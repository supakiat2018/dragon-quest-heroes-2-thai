def apply_part1():
    file_path = 'text_csv/categories/entry_00211_Battle_Guides_Tutorials.csv'
    with open(file_path, 'r', encoding='utf-8-sig') as f:
        reader = list(csv.DictReader(f))
        fieldnames = reader[0].keys()
        
    applied = 0
    for row in reader:
        sidx = int(row['StringIndex'])
        if sidx in translations_part1:
            row['ThaiTranslation'] = translations_part1[sidx]
            applied += 1
            
    with open(file_path, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(reader)
        
    print(f"Applied {applied} translations to {file_path}")

if __name__ == '__main__':
    apply_part1()
