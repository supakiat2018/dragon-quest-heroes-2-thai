def apply_translation():
    file_path = "text_csv/categories/entry_00148_Dungeons_Mazes.csv"
    with open(file_path, "r", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for slot_idx, (thai_name, thai_desc) in DUNGEONS.items():
        base_row = slot_idx * 8
        if base_row + 3 >= len(rows):
            continue

        chunk = rows[base_row:base_row+8]
        chunk[0]["ThaiTranslation"] = thai_name
        chunk[1]["ThaiTranslation"] = thai_name
        chunk[2]["ThaiTranslation"] = thai_desc
        chunk[3]["ThaiTranslation"] = thai_name
        updated += 1

    with open(file_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[SUCCESS] Updated {updated} dungeons in entry_00148_Dungeons_Mazes.csv")

if __name__ == "__main__":
    apply_translation()
