def apply_translation():
    file_path = "text_csv/categories/entry_00036_Story_Quests.csv"
    with open(file_path, "r", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for row_idx, thai_text in STORY_QUESTS_PART2.items():
        if row_idx < len(rows):
            rows[row_idx]["ThaiTranslation"] = thai_text
            updated += 1

    with open(file_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[SUCCESS] Updated {updated} lines in rows 1000-1999 of entry_00036_Story_Quests.csv")

if __name__ == "__main__":
    apply_translation()
