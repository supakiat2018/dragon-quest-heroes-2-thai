def apply_translations(mapping):
    with open(CSV_PATH, "r", encoding="utf-8-sig", newline="") as f:
        reader = list(csv.reader(f))
        
    header = reader[0]
    rows = reader[1:]
    updated = 0
    
    for row in rows:
        str_idx = int(row[2])
        if str_idx in mapping:
            row[6] = mapping[str_idx]
            updated += 1
            
    with open(CSV_PATH, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)
        
    # ซิงค์เข้า Master CSV
    lookup = {(204, int(k)): v for k, v in mapping.items()}
    with open(MASTER_CSV, "r", encoding="utf-8-sig", newline="") as f:
        master_reader = list(csv.reader(f))
    master_header = master_reader[0]
    master_rows = master_reader[1:]
    master_updated = 0
    for row in master_rows:
        eid = int(row[0])
        sidx = int(row[2])
        if (eid, sidx) in lookup:
            row[6] = lookup[(eid, sidx)]
            master_updated += 1
    with open(MASTER_CSV, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(master_header)
        writer.writerows(master_rows)
        
    print(f"อัปเดตคำแปล 100% สำเร็จ: {updated} บรรทัด (ซิงค์เข้า Master: {master_updated} บรรทัด)")

if __name__ == "__main__":
    apply_translations(TRANSLATIONS_100PCT)
