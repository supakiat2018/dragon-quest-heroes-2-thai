def apply_translation():
    file_path = "text_csv/categories/entry_00260_Side_Quest_Rumours.csv"
    with open(file_path, "r", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for q_idx, data in RUMOURS.items():
        base = q_idx * 6
        if base + 5 >= len(rows):
            continue

        chunk = rows[base:base+6]
        if data["title"]:
            chunk[0]["ThaiTranslation"] = data["title"]
            updated += 1
        if data["client"]:
            chunk[1]["ThaiTranslation"] = data["client"]
            updated += 1
        if data["desc"]:
            chunk[2]["ThaiTranslation"] = data["desc"]
            updated += 1
        if data["hint1"]:
            chunk[3]["ThaiTranslation"] = data["hint1"]
            updated += 1
        if data["loc"]:
            chunk[4]["ThaiTranslation"] = data["loc"]
            updated += 1
        if data["hint2"]:
            chunk[5]["ThaiTranslation"] = data["hint2"]
            updated += 1

    with open(file_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[SUCCESS] Updated {updated} fields in entry_00260_Side_Quest_Rumours.csv")

if __name__ == "__main__":
    apply_translation()
