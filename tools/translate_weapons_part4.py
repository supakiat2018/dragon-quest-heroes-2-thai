def apply_translations():
    target_csv = "text_csv/categories/entry_00071_Weapons_Equipment.csv"
    with open(target_csv, "r", encoding="utf-8-sig") as f:
        reader = list(csv.DictReader(f))
        fieldnames = reader[0].keys()

    updated = 0
    for slot_idx, (thai_name, thai_desc) in WEAPONS_PART4.items():
        base_row = slot_idx * 8
        if base_row + 7 >= len(reader):
            continue
            
        chunk = reader[base_row:base_row+8]
        chunk[0]["ThaiTranslation"] = thai_name
        chunk[1]["ThaiTranslation"] = thai_name
        chunk[2]["ThaiTranslation"] = thai_desc
        chunk[3]["ThaiTranslation"] = thai_name
        for off in range(4, 8):
            chunk[off]["ThaiTranslation"] = ""
            
        updated += 1

    with open(target_csv, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(reader)

    print(f"[SUCCESS] Updated {updated} weapons in Part 4!")

if __name__ == "__main__":
    apply_translations()
