def apply_translation():
    file_path = "text_csv/categories/entry_00169_Accolades_Trophies.csv"
    with open(file_path, "r", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys()

    updated = 0
    for slot_idx, (thai_name, thai_desc) in TROPHIES.items():
        base = slot_idx * 8
        if base + 2 >= len(rows):
            continue

        chunk = rows[base:base+8]
        chunk[0]["ThaiTranslation"] = thai_name
        chunk[1]["ThaiTranslation"] = thai_name
        chunk[2]["ThaiTranslation"] = thai_desc
        updated += 3

    with open(file_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[SUCCESS] Updated {updated} fields (43 trophies) in entry_00169_Accolades_Trophies.csv")

if __name__ == "__main__":
    apply_translation()
